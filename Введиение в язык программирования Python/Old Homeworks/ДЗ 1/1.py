'''Задание 1
Пользователь вводит с клавиатуры три числа.
Необходимо найти сумму чисел, произведение
чисел. Результат вычислений вывести на экран.'''
print("Введите 3 числа")

num1 = int(input("введите число 1:"))
num2 = int(input("введите число 2:"))
num3 = int(input("введите число 3:"))

print("Сумма введённых чисел:", num1+num2+num3)
print("Произведение введёных чисел:", num1*num2*num3)
